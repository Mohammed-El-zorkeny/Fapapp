-- Create path tracking table with battery and timezone columns
CREATE TABLE DBS_SALESMAN_PATH_TRACK (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    INVOICE_ID NUMBER NOT NULL,
    SALESMAN_ID NUMBER NOT NULL,
    LATITUDE NUMBER(12, 8) NOT NULL,
    LONGITUDE NUMBER(12, 8) NOT NULL,
    BEARING NUMBER(6, 2) DEFAULT 0.0,
    TRACK_TIME TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP,
    BATTERY_LEVEL NUMBER(3) NOT NULL,
    IS_CHARGING CHAR(1) NOT NULL, -- 'Y' for charging, 'N' for not
    CONSTRAINT PK_PATH_TRACK PRIMARY KEY (ID),
    CONSTRAINT FK_PATH_TRACK_INVOICE FOREIGN KEY (INVOICE_ID) REFERENCES DBS_SAL_INVOICE(ID),
    CONSTRAINT FK_PATH_TRACK_SALESMAN FOREIGN KEY (SALESMAN_ID) REFERENCES DBS_SAL_SALES_MAN(ID)
);
